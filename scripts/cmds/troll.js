  // ১. ম্যানুয়ালি কমান্ড দিলে কাজ করবে (যেমন: .troll)
  onStart: async function ({ event, api, message }) {
    const { threadID, senderID, body } = event;
    const text = (body || "").toLowerCase().trim();
    // কমান্ডের নাম বাদ দিয়ে বাকি টেক্সট চেক করবে
    const prefix = global.GoatBot.config.prefix;
    const commandText = text.replace(prefix + "troll", "").trim();

    return executeTroll(commandText, threadID, senderID, event.messageID, api);
  },

  // ২. অটোমেটিক ট্রিগার (চাইলে কাজ করবে, তবে onStart নিশ্চিত কাজ করবে)
  onChat: async function ({ event, api }) {
    const { threadID, senderID, body } = event;
    
    if (!body || senderID == api.getCurrentUserID()) return;

    const text = body.toLowerCase().trim();
    
    // ইগনোর করবে যদি মেসেজটি কমান্ড দিয়ে শুরু হয়
    if (text.startsWith(global.GoatBot.config.prefix)) return;

    return executeTroll(text, threadID, senderID, event.messageID, api);
  }
